export function presetForProvider(name: string, baseUrl: string): ProviderPreset | undefined {
  return PROVIDER_PRESETS.find(
    (preset) =>
      preset.available &&
      (preset.baseUrl.replace(/\/+$/, "") === baseUrl.replace(/\/+$/, "") ||
        preset.name === name),
  );
}
