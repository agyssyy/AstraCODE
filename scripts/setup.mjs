#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const envPath = path.join(root, ".env");

if (fs.existsSync(envPath)) {
  console.log(".env already exists — leaving it untouched.");
} else {
  const encryptionKey = crypto.randomBytes(32).toString("base64");
  const previewSecret = crypto.randomBytes(32).toString("base64url");
  const content = `# Generated by \`pnpm setup\` on ${new Date().toISOString()}
# Do not commit this file.

WEB_ORIGIN=http://localhost:3000
NEXT_PUBLIC_API_URL=http://localhost:4000
API_INTERNAL_URL=http://127.0.0.1:4000
API_HOST=127.0.0.1
API_PORT=4000

APP_ENCRYPTION_KEY=${encryptionKey}
PREVIEW_SECRET=${previewSecret}

# Optional: use an external PostgreSQL instead of the embedded PGlite database.
DATABASE_URL=
ASTRACODE_DATA_DIR=./data
NODE_ENV=development
`;
  fs.writeFileSync(envPath, content, { mode: 0o600 });
  console.log("Created .env with freshly generated secrets (mode 0600).");
}

const dataDir = path.join(root, "data");
fs.mkdirSync(dataDir, { recursive: true });
console.log("Data directory ready:", dataDir);
console.log("\nNext: pnpm dev");
